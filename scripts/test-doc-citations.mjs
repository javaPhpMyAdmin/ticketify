#!/usr/bin/env node
/**
 * Drift guard for documentation citations — the claims docs make about this repo.
 *
 * WHAT GAP THIS CLOSES
 * --------------------
 * Documentation here rotted repeatedly while the build stayed green.
 * `scripts/test-sql-smoke-coverage.mjs` (PR #145) reconciles the SQL smoke
 * FILE LIST across disk, harness and CI — but it reads no documentation, so
 * prose drifted freely. Three failures this repo already paid for:
 *
 *   1. A doc told readers to run `npm run reset-project` — a script that had
 *      never existed at any revision of package.json (fixed by PR #147).
 *   2. A line-number citation (`supabase/tests/README.md:136-142`) went stale
 *      when maintenance moved the content to 149-156. The citation still
 *      LOOKED plausible — the worst failure mode (fixed by PR #149).
 *   3. Counts in prose stopped matching their source. The repo's answer to
 *      that class is a written no-counts policy (see the "No count is written
 *      here on purpose" paragraph in supabase/tests/README.md); this guard
 *      complements it by checking the OTHER claim style — pointers — instead.
 *
 * This guard reads the docs and the repo and asserts the pointers resolve.
 * It needs no network, no Docker and no timer: it only reads files already in
 * the tree and the git index, so it belongs in the Docker-free master
 * `pnpm test` chain (assertion 7 makes that wiring an invariant rather than a
 * convention).
 *
 * Assertions (8 numbered, plus one unnumbered input gate that runs first — 9
 * reported tests in total; the gate resolves package.json, the git file index
 * and every scanned doc inside `test()` so a broken working tree degrades into
 * one named failure instead of aborting the suite with no diagnostics):
 *   1. every `pnpm …` command cited in a scanned doc resolves to a real
 *      package.json script, a pnpm builtin, or a declared dependency
 *   2. every script reached through a cited command's pnpm chain resolves:
 *      nested `pnpm <other>` segments name existing scripts, and `node <file>`
 *      segments point at tracked files (the nesting rule — see below)
 *   3. every `path:line` citation names a path that exists in the tracked
 *      tree, relative to the repo root
 *   4. every cited line number is inside its file's bounds — bare (`:60`),
 *      range (`:45-71`) and disjoint range (`:4-11,26-45`) all parse, and a
 *      range must not be inverted
 *   5. every `path:line:payload` transcript claim is true: the payload must
 *      appear in the cited lines (see "TRANSCRIPT CITATIONS" below)
 *   6. PARSER FLOOR: the extractor still finds at least one pnpm citation and
 *      one path citation — an empty scan set or a broken regex fails here
 *      instead of reporting success on nothing
 *   7. this guard's own package.json script is declared exactly once and is a
 *      segment of the master chain
 *   8. the master chain string contains no failure-swallowing construct
 *      (`|| true`, `|| :`, `|| exit 0`, `; true`, bare `exit 0`) — because
 *      `chainCommands` splits on `||`, a `pnpm test:doc-citations || true`
 *      segment still satisfies assertion 7's wiring check while the chain
 *      exits 0 with this guard red (CI green, guard red). Same idea as the
 *      SQL smoke guard's "no step can swallow a failure" assertion.
 *
 * WHICH FILES ARE SCANNED — AND WHY NOT THE REST
 * ----------------------------------------------
 * The scan set is EVERY git-tracked `*.md` EXCEPT three prefixes. It is
 * derived from `git ls-files`, never from a hardcoded list, so a newly added
 * doc is covered the moment it is committed — the exact "drop a new file and
 * nothing notices" hole the SQL coverage guard documents.
 *
 *   Scanned: README.md, supabase/tests/README.md and every other tracked
 *   markdown doc outside the exclusions — including the root milestone notes
 *   and the capturas design docs, which carry runnable commands too.
 *
 *   EXCLUDED `docs/legal/`  — GENERATED by `pnpm generate:legal-docs`. Drift
 *     there is the generator's contract (guarded by test:legal-content), and
 *     a hand-edit check would fight the next regeneration.
 *   EXCLUDED `openspec/`    — SDD process records, in three flavours:
 *     `changes/archive/**` is frozen history (rewriting it would falsify the
 *     record), `changes/<active>/**` are working plans that use shorthand
 *     references to then-current code by convention and are validated by the
 *     verify/archive phases, and `specs/**` are requirement documents whose
 *     background prose cites code as it was WHEN THE SPEC WAS WRITTEN
 *     (`useHomeFeed.ts:190-218` in home-month-navigation today points at
 *     content that has since moved, but stays in bounds). A bounds-only
 *     guard would force cosmetic path fixes there while certifying the
 *     deeper staleness — worse than not scanning. Requirements themselves
 *     are enforced by harnesses, not by prose pointers.
 *   EXCLUDED `.agents/`      — today that directory holds only vendored
 *     `skills/`: third-party skills pinned by skills-lock.json, whose
 *     citations are upstream's to maintain; editing them to satisfy this
 *     guard would falsify the vendoring. The prefix is the whole directory
 *     rather than `.agents/skills/` because that is all it contains — the
 *     moment first-party markdown lands there (say `.agents/prompts/`), this
 *     prefix silently excludes it under a reason that no longer applies, and
 *     narrowing it is the required follow-up.
 *
 * THE NESTING RULE (assertion 2)
 * ------------------------------
 * A doc citing `pnpm test:foo` asserts two things: the script exists, and the
 * script does something real. The rule:
 *   - The cited name must be a key of package.json scripts (assertion 1).
 *   - The script's command is then split on `&&`, `;`, `||` and newlines.
 *     Each segment that is `pnpm [run] <other>` is resolved the same way,
 *     recursively (cycle-guarded), so `pnpm test` walks the whole master
 *     chain. Each segment that is `node <file>` must name a tracked file —
 *     that is how "the script exists but its harness was deleted" fails.
 *   - Any other leaf (`expo start`, `tsc --noEmit`, `supabase …`) cannot be
 *     resolved without executing it and is accepted as-is. Stated limit.
 *
 * WHAT COUNTS AS A `pnpm` CITATION
 * --------------------------------
 * Only text a reader may run: inline code spans (`` `pnpm test` ``) and
 * fenced blocks tagged bash/sh/shell/zsh/console. Prose is deliberately NOT
 * scanned — it carries version numbers ("pnpm 9.15.9") and English fragments
 * ("parse pnpm and fell back") that would train people to bypass the guard,
 * and this repo's style puts every runnable command in code markup anyway.
 * Untagged fences are trees and transcripts (README's structure block says
 * "pnpm patchedDependencies" as prose), so they are not scanned either.
 *
 * A cited name resolves through pnpm's own chain, in order:
 *   1. package.json script — the primary assertion;
 *   2. pnpm's CLI builtins (install, add, run, exec, dlx, …). The npm-compat
 *      lifecycle aliases (test, start, stop, restart) are deliberately NOT
 *      builtins here — pnpm resolves them from scripts, so they must too;
 *   3. a declared dependency whose package name matches (pnpm falls back to
 *      node_modules/.bin — verified: `pnpm expo --version` runs). Checked
 *      against package.json, never node_modules, so the verdict is identical
 *      on machines with and without an install. Known under-strict corner: a
 *      declared package that exposes no same-named bin would pass here and
 *      fail at the prompt; none is cited today.
 * An unknown name fails CLOSED — that is the `reset-project` class.
 *
 * TRANSCRIPT CITATIONS (assertion 5)
 * ----------------------------------
 * `git check-ignore -v` prints `source:linenum:pattern`. README quotes such a
 * transcript (`.gitignore:50:/android`), and that is a checkable claim: the
 * cited line must actually contain the quoted pattern. This is the one place
 * line CONTENT is verified mechanically, because the content is part of the
 * citation itself — and it is exactly how a stale transcript was caught on
 * main (reported in this change's commit body).
 *
 * PARSED SHAPES, for reference when this guard fails:
 *   pnpm     `pnpm <name>` / `pnpm run <name>` inside an inline code span or
 *            a shell-tagged fence; the name starts with a letter and runs to
 *            the next whitespace (args are not checked — `pnpm install
 *            --frozen-lockfile` asserts `install`, not the flag)
 *   path     maximal run of [A-Za-z0-9_./-] that contains a `/`, or ends in
 *            a letter-suffixed extension (`format.ts`), or is a dotfile
 *            (`.gitignore`), immediately followed by `:digits…` (each
 *            number capped at 10 digits, so an absurd line number never
 *            reaches an allocation — no real file has 10-digit lines)
 *
 * WHAT THIS DOES NOT PROTECT AGAINST
 * ----------------------------------
 *   * Ranged citations are bounds-checked, not content-checked.
 *     `src/lib/format.ts:45-71` is verified for existence and bounds; content
 *     that MOVES but stays within plausible bounds is a human-audit class —
 *     the citation still looks right while saying something else (done by
 *     audit, not by machine). The preferred form for a contract-critical
 *     claim is `path:line:payload`, the transcript form, which IS
 *     content-verified (see "TRANSCRIPT CITATIONS" above).
 *   * Citations written in prose without code markup, and direct
 *     `node <file>` citations outside a pnpm chain — not checked, by the
 *     "what counts as a citation" rule above.
 *   * `host:443`-style targets would parse as a path citation (letters-only
 *     TLD passes the shape rule). None exists in the scan set today; if one
 *     is added, this guard will name it and the fix is to keep the port out
 *     of citation shape (backtick the URL alone or rephrase).
 *   * Windows-style paths (`C:\…`) and paths that legitimately contain `:`
 *     cannot be resolved repo-root-relative on every machine, so tokens with
 *     backslashes or drive-letter shapes are not treated as citations.
 *   * Tracked symlinks are followed: a citation that resolves through one is
 *     read wherever it points, outside the tree it appears to name. The repo
 *     has zero tracked symlinks today, and planting one requires commit
 *     access — the same trust boundary as the Windows-path limit above.
 *   * PARTIAL extractor loss. Assertion 6's floor fires only on TOTAL loss
 *     (zero citations of a class); a mistagged fence or a broken region mask
 *     that drops SOME citations while others survive passes the floor and
 *     reports success on a partial scan. The floor catches the guillotine,
 *     not the leak — a human diffing the extracted set against the docs is
 *     the check for that.
 *   * Its own wiring. Assertion 7 makes unwiring loud on the next run; no
 *     assertion inside a guard can force the chain to keep running it —
 *     same honest limit the SQL coverage guard records.
 *
 * Usage: pnpm test:doc-citations  (or: node scripts/test-doc-citations.mjs)
 */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const packagePath = join(root, 'package.json');

/** This file, as package.json spells it. Used by assertion 7 to find the
 *  script name that runs the guard, so the wiring check never hardcodes a
 *  second copy of the name that could drift. */
const GUARD_FILE = 'scripts/test-doc-citations.mjs';

/** Markdown under these prefixes is deliberately not scanned. Each exclusion
 *  is a decision with a reason — see the header's "WHICH FILES ARE SCANNED". */
const EXCLUDED_PREFIXES = ['docs/legal/', 'openspec/', '.agents/'];

/** The scan set must always contain the onboarding path. A git listing that
 *  somehow loses these is an input failure, not "0 docs, all green". */
const REQUIRED_DOCS = ['README.md', 'supabase/tests/README.md'];

/** Fence language tags whose content is runnable shell. */
const SHELL_LANGS = new Set(['bash', 'sh', 'shell', 'zsh', 'console']);

/** pnpm's own CLI commands. Deliberately EXCLUDES the npm-compat lifecycle
 *  aliases (test, start, stop, restart): pnpm resolves those from scripts, so
 *  a cited `pnpm start` must fail here the moment scripts.start disappears. */
const PNPM_BUILTINS = new Set([
  'install', 'add', 'remove', 'update', 'exec', 'dlx', 'run', 'list', 'why',
  'outdated', 'audit', 'dedupe', 'import', 'licenses', 'root', 'bin', 'store',
  'config', 'patch', 'patch-commit', 'publish', 'pack', 'env', 'init',
  'approve-builds',
]);

let passed = 0;
let failed = 0;

async function test(name, fn) {
  const started = Date.now();
  try {
    await fn();
    passed += 1;
    console.log(`  ok    ${name} (${Date.now() - started}ms)`);
  } catch (err) {
    failed += 1;
    console.error(`  FAIL  ${name}`);
    console.error(String((err && err.stack) || err));
  }
}

/** Splits a shell command chain into its individual commands. `&&` short-circuits
 *  on failure, so it may never hide a command; `;`, `||` and newlines do not. */
function chainCommands(command) {
  return command
    .split(/\s*(?:&&|;|\|\||\n)\s*/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

/** Is `pnpm <name>` this exact command? Tolerates `pnpm run <name>` and
 *  hard-anchors the end so args and sibling names never confuse it. */
function isPnpmScript(command, name) {
  return new RegExp(`^pnpm(?:\\s+run)?\\s+${name}$`).test(command);
}

/** Shell constructs that turn a failing command into a passing one: a trailing
 *  `|| true` / `|| exit 0` / `|| :`, a `; true` tail, or a bare `exit 0`.
 *  Identical to the SQL smoke guard's SWALLOW_PATTERN, because the defect is
 *  identical: `chainCommands` splits on `||`, so
 *  `pnpm test:doc-citations || true` yields `['pnpm test:doc-citations',
 *  'true']` — assertion 7 matches the first segment and stays green while the
 *  chain swallows this guard's exit status. Assertion 8 checks the raw chain
 *  string against this pattern so the suppression itself is the failure. */
const SWALLOW_PATTERN = /(?:\|\||;|&&)\s*(?:true\b|:|exit\s+0\b)|\bexit\s+0\b/;

/** Every git-tracked file, repo-root-relative. The tracked set — not the
 *  working tree — decides existence, so an untracked local scratch file can
 *  never make this guard pass on one machine and fail on another. */
function trackedFiles() {
  const out = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' });
  return new Set(out.split('\0').filter(Boolean));
}

/** Code regions of a markdown doc: fenced blocks (with their language) and
 *  inline code spans. Offsets are into the ORIGINAL source, so a match index
 *  found in a region still maps to the same document line. */
function codeRegions(src) {
  const regions = [];
  const lines = src.split('\n');
  let offset = 0;
  let open = null;

  for (const line of lines) {
    const m = /^(\s*)(`{3,})\s*([A-Za-z0-9-]*)\s*$/.exec(line);
    if (m) {
      if (!open) {
        open = { marker: m[2], lang: (m[3] || '').toLowerCase(), startOffset: offset };
      } else if (m[2].length >= open.marker.length && !m[3]) {
        regions.push({
          kind: 'fence',
          lang: open.lang,
          offset: open.startOffset,
          text: src.slice(open.startOffset, offset),
        });
        open = null;
      }
    }
    offset += line.length + 1;
  }
  // An unclosed fence is still content a reader sees — keep it.
  if (open) {
    regions.push({ kind: 'fence', lang: open.lang, offset: open.startOffset, text: src.slice(open.startOffset) });
  }

  // Inline spans, found on a copy with fences blanked out (length- and
  // offset-preserving) so a fence's triple backticks cannot open a span.
  let masked = src;
  for (const r of regions) {
    masked = masked.slice(0, r.offset) + r.text.replace(/[^\n]/g, ' ') + masked.slice(r.offset + r.text.length);
  }
  for (const m of masked.matchAll(/``([^`]+)``|`([^`\n]+)`/g)) {
    regions.push({ kind: 'span', lang: '', offset: m.index, text: m[1] ?? m[2] });
  }
  return regions;
}

/** 1-based document line containing `offset`. */
function lineAt(src, offset) {
  let line = 1;
  for (let i = 0; i < offset; i += 1) if (src[i] === '\n') line += 1;
  return line;
}

/** Every `pnpm <name>` a reader may run: inside inline code spans, or inside
 *  shell-tagged fences. See the header for why prose and untagged fences are
 *  deliberately out. */
function pnpmCitations(src) {
  const out = [];
  const regions = codeRegions(src).filter((r) => r.kind === 'span' || SHELL_LANGS.has(r.lang));
  const pattern = /\bpnpm(?:\s+run)?\s+([A-Za-z][A-Za-z0-9:_.-]*)/g;
  for (const region of regions) {
    for (const m of region.text.matchAll(pattern)) {
      out.push({ name: m[1], offset: region.offset + m.index, raw: m[0] });
    }
  }
  return out;
}

/** Shape rules for "is this token a path citation?": a maximal run of path
 *  characters that contains a `/`, or ends in a letter-suffixed extension, or
 *  is a dotfile. This is what rejects `7:1` (contrast), `14:30` (time) and
 *  `1:1` (ratio) while accepting `format.ts:45` and `.gitignore:50`.
 *  Each number run is capped at 10 digits: an absurd line number must not
 *  reach assertion 5's allocation, and no real file has 10-digit lines. */
const PATH_CITATION =
  /(?<![A-Za-z0-9_./\\-])([A-Za-z0-9_.][A-Za-z0-9_./-]*):(\d{1,10}(?:-\d{1,10})?(?:,\d{1,10}(?:-\d{1,10})?)*)(?::([^\s`"'()\[\]]+))?/g;

function pathShapeOk(path) {
  if (path.includes('//')) return false; // URL continuation, not a path
  if (path.includes('/')) return true;
  if (/^\.[A-Za-z0-9_.-]+$/.test(path)) return true; // dotfile (.gitignore)
  return /\.[A-Za-z][A-Za-z0-9]*$/.test(path); // has a lettered extension
}

/** Every `path:line…` citation in the doc — prose, spans and fences alike,
 *  because a pointer is a promise wherever it is written. The optional third
 *  field is the `git check-ignore -v` transcript payload (see header). */
function pathCitations(src) {
  const out = [];
  for (const m of src.matchAll(PATH_CITATION)) {
    if (!pathShapeOk(m[1])) continue;
    // Did the shape stop at a space while the real token continued? The match
    // begins right after a space whenever the token itself contains one —
    // `capturas/Paywall PRO/DESIGN.md:12` matches starting at `PRO/…`. Walk
    // back over the separating spaces and the path-shaped fragment before
    // them: if that fragment itself passes the path shape rule, `m[0]` is
    // only the TAIL of the token and assertion 3 must say so instead of
    // blaming a file nobody wrote.
    let cut = m.index;
    while (cut > 0 && src[cut - 1] === ' ') cut -= 1;
    let start = cut;
    while (start > 0 && /[A-Za-z0-9_./\\-]/.test(src[start - 1])) start -= 1;
    const prefix = src.slice(start, cut);
    const choppedAtSpace = cut < m.index && prefix.length > 0 && pathShapeOk(prefix);
    out.push({
      path: m[1],
      spec: m[2],
      payload: m[3],
      offset: m.index,
      raw: m[0],
      choppedAtSpace,
      fullToken: choppedAtSpace ? src.slice(start, m.index + m[0].length) : null,
      fullPath: choppedAtSpace ? src.slice(start, m.index + m[1].length) : null,
    });
  }
  return out;
}

/** Parses `45-71`, `60`, `4-11,26-45` into [[start, end], …]. */
function lineSpecRanges(spec) {
  return spec.split(',').map((part) => {
    const [start, end] = part.split('-').map(Number);
    return [start, end === undefined ? start : end];
  });
}

/** File content split into lines, with a trailing newline NOT counted as an
 *  extra line — so a citation of `file:<n>` means the nth line a human sees. */
function contentLines(source) {
  const lines = source.split('\n');
  if (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  return lines;
}

async function run() {
  console.log('\n[doc-citations] Documentation citation drift guard\n');

  const inputs = {};
  await test('inputs resolve: package.json, the git file index and the scanned docs', () => {
    const pkg = JSON.parse(readFileSync(packagePath, 'utf8'));
    assert.ok(
      typeof pkg.scripts === 'object' && pkg.scripts !== null,
      'package.json must declare a scripts object',
    );
    assert.ok(
      typeof pkg.scripts.test === 'string',
      'package.json scripts["test"] must be a string so this guard can read the master chain',
    );
    inputs.pkg = pkg;
    inputs.deps = { ...(pkg.dependencies || {}), ...(pkg.devDependencies || {}) };

    inputs.tracked = trackedFiles();

    const docs = [...inputs.tracked]
      .filter((f) => f.endsWith('.md') && !EXCLUDED_PREFIXES.some((p) => f.startsWith(p)))
      .sort();
    for (const required of REQUIRED_DOCS) {
      assert.ok(docs.includes(required), `the scan set must include ${required}`);
    }
    assert.ok(docs.length > 0, 'the scan set must not be empty');

    inputs.docs = docs.map((file) => ({ file, src: readFileSync(join(root, file), 'utf8') }));
    inputs.ready = true;
  });

  const ready = 'ready' in inputs && inputs.ready;
  const docs = ready ? inputs.docs : [];
  const pkg = ready ? inputs.pkg : { scripts: {}, test: '' };
  const deps = ready ? inputs.deps : {};
  const tracked = ready ? inputs.tracked : new Set();

  const citations = { pnpm: [], path: [] };
  for (const doc of docs) {
    for (const c of pnpmCitations(doc.src)) citations.pnpm.push({ doc: doc.file, src: doc.src, ...c });
    for (const c of pathCitations(doc.src)) citations.path.push({ doc: doc.file, src: doc.src, ...c });
  }
  // Offsets are PER-DOCUMENT, so an offset-only sort interleaves documents in
  // an order matching neither the scan order nor document order — it scrambled
  // this guard's own offender lists. Group by document first (the scan order),
  // then by offset within the document; that also puts a document's fence- and
  // span-extracted pnpm citations into true in-document order.
  const byDocThenOffset = (a, b) =>
    a.doc !== b.doc ? (a.doc < b.doc ? -1 : 1) : a.offset - b.offset;
  citations.pnpm.sort(byDocThenOffset);
  citations.path.sort(byDocThenOffset);

  console.log(
    `[doc-citations] scan — ${docs.length} docs, ` +
      `${citations.pnpm.length} pnpm citations, ${citations.path.length} path citations\n`,
  );

  const at = (c) => `${c.doc}:${lineAt(c.src, c.offset)}`;

  // ── 1. Every cited pnpm command resolves ──────────────────────────────
  await test('every `pnpm …` command cited in a scanned doc resolves to a real script, pnpm builtin or declared dependency', () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    const offenders = citations.pnpm
      .filter((c) => !pkg.scripts[c.name] && !PNPM_BUILTINS.has(c.name) && !deps[c.name])
      .map(
        (c) =>
          `${at(c)}: \`pnpm ${c.name}\` — no scripts["${c.name}"], not a pnpm builtin, ` +
          'not a declared dependency',
      );
    assert.deepEqual(
      offenders,
      [],
      'a cited command a reader cannot run is the `reset-project` defect class:\n  - ' +
        `${offenders.join('\n  - ')}\n` +
        'add the script to package.json, fix the citation, or — only if the name is a new\n' +
        'pnpm CLI command or a package-provided binary — extend the rule that admits it\n' +
        '(PNPM_BUILTINS / declared-dependency fallback, see the header of ' +
        'scripts/test-doc-citations.mjs).',
    );
  });

  // ── 2. The chain behind a cited command resolves ──────────────────────
  //
  // A script that exists but shells out to a deleted harness is the same rot
  // as a script that does not exist. `pnpm test` is cited in both onboarding
  // READMEs, so this walks the entire master chain: every nested `pnpm …`
  // segment must name a script, every `node <file>` segment a tracked file.
  await test("every script reached through a cited command's pnpm chain resolves to scripts and tracked files", () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    const visited = new Set();
    const queue = [];
    for (const c of citations.pnpm) {
      if (pkg.scripts[c.name]) queue.push({ name: c.name, origin: c, path: [c.name] });
    }
    const offenders = [];

    while (queue.length > 0) {
      const { name, origin, path } = queue.shift();
      if (visited.has(name)) continue;
      visited.add(name);

      const command = pkg.scripts[name];
      if (typeof command !== 'string') {
        offenders.push(
          `${at(origin)}: \`${path.join(' → ')}\` — scripts["${name}"] is missing`,
        );
        continue;
      }

      for (const segment of chainCommands(command)) {
        const nested = /^pnpm(?:\s+run)?\s+([A-Za-z][A-Za-z0-9:_.-]*)$/.exec(segment);
        if (nested) {
          const next = nested[1];
          if (pkg.scripts[next] !== undefined) {
            queue.push({ name: next, origin, path: [...path, next] });
          } else if (!PNPM_BUILTINS.has(next) && !deps[next]) {
            offenders.push(
              `${at(origin)}: \`${path.join(' → ')} → ${next}\` — scripts["${name}"] runs ` +
                `\`pnpm ${next}\`, which is not a script, a pnpm builtin or a declared dependency`,
            );
          }
          continue;
        }

        if (/^node(\s|$)/.test(segment)) {
          const tokens = segment.split(/\s+/).slice(1);
          for (const token of tokens) {
            if (token.startsWith('-')) continue; // flags, incl. their =values
            if (/^["'`]/.test(token)) break; // inline code (`node -e '…'`)
            const file = token.replace(/^["']|["']$/g, '');
            if (file.includes('/') || /\.(mjs|cjs|js|json)$/.test(file)) {
              if (!tracked.has(file)) {
                // Same wrong-story problem as assertion 3: a file that exists
                // on disk but was never `git add`ed has a CORRECT path — the
                // fix is to track it, not to rewrite the script.
                const onDisk = existsSync(join(root, file));
                offenders.push(
                  `${at(origin)}: \`${path.join(' → ')}\` — scripts["${name}"] runs ` +
                    `\`node ${file}\`, which is ` +
                    (onDisk
                      ? `present on disk but NOT tracked — \`git add ${file}\` if the path is ` +
                        'correct, or fix the script'
                      : 'not a tracked file'),
                );
              }
            }
            break; // only the first non-flag token is the script file
          }
        }
        // Any other leaf (expo, tsc, supabase, curl …) cannot be resolved
        // without executing it — accepted, as the header states.
      }
    }

    assert.deepEqual(
      offenders,
      [],
      'the chain behind a cited command must resolve all the way down:\n  - ' +
        `${offenders.join('\n  - ')}\n` +
        'a script whose target file was deleted still "exists" in package.json while ' +
        'failing for every reader — fix the script or the citation.',
    );
  });

  // ── 3. Every cited path exists in the tracked tree ────────────────────
  await test('every path:line citation names a path that exists in the tracked tree', () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    const offenders = citations.path
      .filter((c) => !tracked.has(c.path))
      .map((c) => {
        // The path shape stops at the first space, so `c.path` may be only
        // the tail of what the contributor actually wrote. Blaming the tail
        // would name a file nobody wrote and tell them to "fix" a correct
        // citation — say what happened instead.
        if (c.choppedAtSpace) {
          const verdict = tracked.has(c.fullPath)
            ? `\`${c.fullPath}\` IS tracked — the citation content is right, but this guard's ` +
              'path shape stops at the first space and cannot check it as written'
            : `no tracked file at \`${c.fullPath}\` either`;
          return (
            `${at(c)}: cited \`${c.fullToken}\` — the shape read only its tail \`${c.raw}\`: ` +
            `${verdict}. Keep cited paths space-free, or rephrase the citation`
          );
        }
        // The path may be perfectly correct and merely never `git add`ed —
        // "fix the path" would send the contributor to rewrite a right path.
        if (existsSync(join(root, c.path))) {
          return (
            `${at(c)}: \`${c.raw}\` — ${c.path} exists on disk but is NOT tracked; ` +
            `\`git add ${c.path}\` if the citation is correct, otherwise fix the path`
          );
        }
        return `${at(c)}: \`${c.raw}\` — no tracked file at ${c.path} (repo-root-relative)`;
      });
    assert.deepEqual(
      offenders,
      [],
      'a citation pointing at nothing is the deleted-file defect class:\n  - ' +
        `${offenders.join('\n  - ')}\n` +
        'fix the path (it is resolved relative to the repo root), or drop the citation. ' +
        'Paths that legitimately contain `:` or backslashes are not parsed as citations ' +
        'at all, and a path containing a SPACE is parsed only up to that space — in both ' +
        'cases keep cited paths in the plain `dir/name.ext:line` shape or rephrase — see ' +
        'the header.',
    );
  });

  // ── 4. Every cited line number is inside the file ─────────────────────
  await test("every cited line number is within its file's bounds", () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    const offenders = [];
    for (const c of citations.path) {
      if (!tracked.has(c.path)) continue; // already reported by assertion 3
      let lines;
      try {
        lines = contentLines(readFileSync(join(root, c.path), 'utf8'));
      } catch (err) {
        if (err.code === 'ENOENT') {
          // Tracked in git but absent from disk: sparse checkout, local
          // delete, half-applied merge. Prescribing "re-cite it" would send
          // the contributor to rewrite a correct citation — the defect is
          // the worktree, not the doc.
          offenders.push(
            `${at(c)}: \`${c.raw}\` — ${c.path} is in the git index but MISSING from the ` +
              `working tree (sparse checkout, local delete, half-applied merge); run \`git ` +
              `checkout -- ${c.path}\`. This is a WORKTREE problem, not a citation problem`,
          );
        } else {
          offenders.push(
            `${at(c)}: \`${c.raw}\` — ${c.path} is tracked but unreadable: ${err.code || err.message}`,
          );
        }
        continue;
      }
      for (const [start, end] of lineSpecRanges(c.spec)) {
        if (start > end) {
          offenders.push(`${at(c)}: \`${c.raw}\` — inverted range ${start}-${end}`);
        } else if (start < 1 || end > lines.length) {
          offenders.push(
            `${at(c)}: \`${c.raw}\` — line ${start}-${end} is outside ${c.path} ` +
              `(file has ${lines.length} line${lines.length === 1 ? '' : 's'})`,
          );
        }
      }
    }
    assert.deepEqual(
      offenders,
      [],
      'a line number past EOF — or an inverted range — is the silently-stale citation ' +
        'defect class; the citation looks plausible while pointing at nothing:\n  - ' +
        `${offenders.join('\n  - ')}\n` +
        're-locate the content and re-cite it — except for an offender that says the file ' +
        'is missing from the WORKING TREE: that one is fixed by restoring the file ' +
        '(`git checkout -- <path>`), never by re-citing. Note this guard checks BOUNDS, ' +
        'not content: a moved block that is still in bounds needs a human review.',
    );
  });

  // ── 5. Transcript claims are true of the cited lines ──────────────────
  await test('every path:line:payload transcript claim is true of the cited lines', () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    const offenders = [];
    for (const c of citations.path) {
      if (!c.payload || !tracked.has(c.path)) continue;
      let lines;
      try {
        lines = contentLines(readFileSync(join(root, c.path), 'utf8'));
      } catch {
        continue; // assertion 3/4 already named the file
      }
      const ranges = lineSpecRanges(c.spec);
      // Clamp to the file BEFORE allocating. Assertion 4 already reports
      // out-of-bounds ranges; building `end - start + 1` slots unclamped let
      // `some.md:1-3000000000:payload` against a 2-line file allocate a
      // multi-GB array, fatal-OOM the process (exit 134) and kill the whole
      // master chain with no report for the assertions that follow. The
      // clamped slice reads exactly the lines that can exist, so the payload
      // verdict is unchanged for every in-bounds and out-of-bounds range.
      const cited = ranges.flatMap(([start, end]) => {
        const lo = Math.max(1, start);
        const hi = Math.min(lines.length, end);
        if (lo > hi) return []; // entirely outside the file — assertion 4 owns it
        return Array.from({ length: hi - lo + 1 }, (_, i) => lines[lo - 1 + i] ?? '');
      });
      if (!cited.some((line) => line.includes(c.payload))) {
        offenders.push(
          `${at(c)}: \`${c.raw}\` — none of the cited line(s) ${c.spec} in ${c.path} ` +
            `contains \`${c.payload}\` (line ${ranges[0][0]} reads: ` +
            `${JSON.stringify((lines[ranges[0][0] - 1] ?? '(past EOF)').slice(0, 90))})`,
        );
      }
    }
    assert.deepEqual(
      offenders,
      [],
      'a quoted tool transcript is a citation of both the line AND its content — ' +
        '`git check-ignore -v` style output going stale is exactly the defect this ' +
        'guards against:\n  - ' +
        `${offenders.join('\n  - ')}\n` +
        're-run the tool and quote its real output.',
    );
  });

  // ── 6. PARSER FLOOR: the extractor must not quietly see nothing ───────
  //
  // Assertions 1-5 all pass vacuously on an empty citation list. The scan set
  // itself is pinned by the input gate, but a broken region mask or a mangled
  // regex could still drop every citation while the docs keep their pointers.
  // A floor of one per citation class catches total extraction loss; it
  // cannot catch PARTIAL loss — that limit is stated in the header's
  // "WHAT THIS DOES NOT PROTECT AGAINST" (PARTIAL extractor loss).
  await test('the extractor still finds citations (parser floor: at least one pnpm and one path citation)', () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    assert.ok(
      citations.pnpm.length > 0,
      'no `pnpm …` citation was extracted from any scanned doc — both onboarding ' +
        'READMEs carry command tables, so this means the extractor or the scan set broke',
    );
    assert.ok(
      citations.path.length > 0,
      'no `path:line` citation was extracted from any scanned doc — README.md cites ' +
        'source files by line, so this means the extractor or the scan set broke',
    );
  });

  // ── 7. The guard cannot be unwired without saying so ──────────────────
  //
  // Same honest limit as the SQL coverage guard's wiring assertion: this fires
  // when the guard RUNS, so it makes removal loud on the next invocation, it
  // cannot make the chain keep running it.
  await test("this guard's own script IS a segment of the master `test` chain", () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    const owners = Object.keys(pkg.scripts).filter((name) =>
      String(pkg.scripts[name]).includes(GUARD_FILE),
    );
    assert.equal(
      owners.length,
      1,
      `package.json must declare exactly one script whose command runs ${GUARD_FILE}, ` +
        `found ${owners.length}: ${owners.join(', ') || '(none)'} — without that entry the ` +
        'guard cannot even be invoked by name',
    );
    const guardScript = owners[0];
    const segments = chainCommands(pkg.scripts.test);
    const wired = segments.filter((cmd) => isPnpmScript(cmd, guardScript));
    assert.ok(
      wired.length > 0,
      `this guard is NOT in the master \`pnpm test\` chain — package.json scripts["${guardScript}"] ` +
        `runs it, but scripts["test"] never calls \`pnpm ${guardScript}\`. Master chain segments:\n  ` +
        `${segments.join('\n  ')}\n` +
        `append \`&& pnpm ${guardScript}\` to scripts["test"], or documentation citations ` +
        'stop being checked while this guard keeps reporting success when run by hand.',
    );
  });

  // ── 8. The chain must not be able to swallow this guard's exit status ──
  //
  // Assertion 7 proves the guard is a segment; it cannot prove the segment's
  // exit status survives. `chainCommands` splits on `||`, so
  // `pnpm test:doc-citations || true` yields ['pnpm test:doc-citations', 'true']
  // — the wiring check matches the first, stays green, and the master chain
  // exits 0 while this guard prints FAIL. The SQL smoke guard treats exactly
  // this as a first-class assertion ("no step can swallow a smoke failure");
  // this is its master-chain counterpart, run against the raw chain string so
  // the split can never hide it.
  await test('the master `test` chain contains no failure-swallowing construct', () => {
    assert.ok(ready, 'inputs did not resolve — see the "inputs resolve" failure above');
    const hit = SWALLOW_PATTERN.exec(pkg.scripts.test);
    if (hit) {
      assert.fail(
        `package.json scripts["test"] swallows failures via \`${hit[0].trim()}\`: a chain ` +
          'segment that cannot fail lets this guard print FAIL while `pnpm test` still ' +
          'exits 0 — CI green with the guard red, and assertion 7 cannot see it because ' +
          'chainCommands splits on `||` before the wiring check runs. Remove the ' +
          'suppression. Checked for: `|| true`, `|| :`, `|| exit 0`, `; true`, `&& true`, ' +
          'and a bare `exit 0`.',
      );
    }
  });

  console.log(`\n[doc-citations] ${passed} passed, ${failed} failed`);
  if (failed > 0) process.exit(1);
}

run().catch((err) => {
  console.error('[doc-citations] harness crashed:', err);
  process.exit(1);
});
